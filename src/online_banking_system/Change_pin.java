    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        if(account_no.getText().length()<=0||pin.getPassword().toString().length()<=0||
            cpin.getPassword().toString().length()<=0)
        {
            error.setText("Enter all Data.");
        }else{

            try{

                char p[]=pin.getPassword();

                char cp[]=cpin.getPassword();
                String pas=String.valueOf(p);
                String cpas=String.valueOf(cp);
                if(pas.equals(cpas)){
                    String url = "jdbc:mysql://localhost:3306/online_banking";

                    String sql = "UPDATE customers SET pin=? WHERE account_no =?";
                    Connection conn  = DriverManager.getConnection(url,"root","root");
                    PreparedStatement ps=conn.prepareStatement(sql);

                    ps.setString(1, pas);
                    ps.setString(2, account_no.getText());

                    int result = ps.executeUpdate();
                    if(result > 0){
                        JOptionPane.showMessageDialog(null,"PIN changed successfully");
                    }else{
                        JOptionPane.showMessageDialog(null,"Account Number not found");
                    }
                }else{
                    error.setText("PIN and confirm PIN are not matched");
                    pin.setText(null);
                    cpin.setText(null);
                }

            }catch(Exception ex)
            {
                JOptionPane.showMessageDialog(null,""+ex);
            }
        }

    }//GEN-LAST:event_jButton1ActionPerformed

