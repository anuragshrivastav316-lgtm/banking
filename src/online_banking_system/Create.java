    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
         if(account.getText().length()<=0||number.getText().length()<=0||name.getText().length()<=0||email.getText().length()<=0||
           pin.getPassword().toString().length()<=0||cpin.getPassword().toString().length()<=0||address.getText().length()<=0||blance.getText().length()<=0)
        {
              error.setText("Enter all data's");
        }else{
        
            try{
            
                 String co=account.getText().trim();
                 String mo=number.getText().trim();
                 String ema=email.getText().trim();
                 String contact="[6789]{1}[0-9]{6}";
                 String mobile="[6789]{1}[0-9]{9}";
                 String email_reg="[a-zA-ZA-z0-9]+@+[a-zA-ZA-z]+.+[a-zA-zA-z]+$";
                 
                  
                    if(!(Pattern.matches(contact, co)))
                {
                    error.setText("Enter valid Account No. ");
                    return;
                }
                    if(!(Pattern.matches(email_reg,ema)))
                {
                    error.setText("Enter valid email");
                    return;
                }
                     if(!(Pattern.matches(contact, co)))
                {
                    error.setText("Enter valid Mobile No. ");
                    return;
                }
                
                
                
                 char p[]=pin.getPassword();

                char cp[]=cpin.getPassword();
                String pas=String.valueOf(p);
                String cpas=String.valueOf(cp);
                if(pas.equals(cpas))
                {
                
                    String url = "jdbc:mysql://localhost:3306/online_banking";

                    String sql = "insert into customers values(?,?,?,?,?,?,?,?)";
                    Connection conn  = DriverManager.getConnection(url,"root","root");
                    PreparedStatement ps=conn.prepareStatement(sql);

                    ps.setString(1, account.getText());
                    ps.setString(2, name.getText());
                    ps.setString(3, number.getText());
                    ps.setString(4, email.getText());
                    ps.setString(5, address.getText());
                    ps.setString(6,type.getSelectedItem().toString());
                    ps.setString(7, pas);
                    ps.setString(8, blance.getText());

                    int result = ps.executeUpdate();
                    if(result > 0){
                        JOptionPane.showMessageDialog(null,"PIN Create Successfully");
                    }else{
                        JOptionPane.showMessageDialog(null,"Data send unsuccess");
                    }
                }
            
            }catch(Exception ex)
            {
                JOptionPane.showMessageDialog(null,""+ex);
            }
        
        
        }
    }//GEN-LAST:event_jButton1ActionPerformed

