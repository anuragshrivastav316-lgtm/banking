private void loadData() {

      DefaultTableModel model =
        (DefaultTableModel) jTable1.getModel();

model.setRowCount(0);

String sql = "SELECT * FROM customers";

try {

    Connection con = DriverManager.getConnection(
        "jdbc:mysql://localhost:3306/online_banking",
        "root",
        "root"
    );

    PreparedStatement pst = con.prepareStatement(sql);

    ResultSet rs = pst.executeQuery();

    int totalCustomer = 0;
    double totalBalance = 0;

    while (rs.next()) {

        totalCustomer++;

        // Total balance calculate
        totalBalance += rs.getBigDecimal("balance").doubleValue();

        model.addRow(new Object[]{

            rs.getLong("account_no"),
            rs.getString("name"),
            rs.getString("mobile"),
            rs.getString("account_type"),
            rs.getBigDecimal("balance")

        });
    }

    // Total Customer label
    Tcustomer.setText(String.valueOf(totalCustomer));

    // Total Balance label
    Tbalance.setText(String.format("₹ "+"%.2f", totalBalance));

    if (totalCustomer == 0) {

        JOptionPane.showMessageDialog(
            this,
            "No customers found!"
        );
    }

    rs.close();
    pst.close();
    con.close();

} catch (Exception e) {

    JOptionPane.showMessageDialog(
        this,
        "Database Error: " + e.getMessage()
    );
}
        
  }
    
    
