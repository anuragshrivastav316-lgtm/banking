    private void searchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchActionPerformed
        // TODO add your handling code here:

        String enteredPin = Pin.getText().trim();

        if (enteredPin.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter Account No.");
            return;
        }

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");

            Connection con = DriverManager.getConnection(
                "jdbc:mysql://localhost:3306/online_banking",
                "root",
                "root"
            );

            String sql = "SELECT address, mobile, account_type, email, name, balance FROM customers WHERE account_no = ?";

            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, enteredPin);

            ResultSet rs = pst.executeQuery();

            if (rs.next()) {

                // MySQL se data lekar labels me set
                Number.setText(rs.getString("mobile"));
                Name.setText(rs.getString("name"));
                adress.setText(rs.getString("address"));
                type.setText(rs.getString("account_type"));
                email.setText(rs.getString("email"));                
                amount.setText("₹ "+rs.getString("balance"));

            } else {

                JOptionPane.showMessageDialog(this, "Invalid PIN");

                amount.setText("");
                Name.setText("");
                Number.setText("");
                adress.setText("");
                email.setText("");
                type.setText("");
            }

            rs.close();
            pst.close();
            con.close();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_searchActionPerformed

