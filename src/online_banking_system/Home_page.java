    private void loadAccountData(String accountNo) {

    try {
//        class.forName("com.mysql.cj.jdbc.Driver");

        Connection con = DriverManager.getConnection(
            "jdbc:mysql://localhost:3306/online_banking",
            "root",
            "root"
        );

        String sql = "SELECT account_no, name, account_type, balance "
                   + "FROM customers WHERE account_no=?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setLong(1, Long.parseLong(accountNo));

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            account.setText(rs.getString("account_no"));

            Name.setText(rs.getString("name"));
            
            uname.setText(rs.getString("name"));

            type.setText(rs.getString("account_type"));

            Blance.setText("₹ " + rs.getString("balance"));

        }

        rs.close();
        pst.close();
        con.close();

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage()
        );
    }
}

