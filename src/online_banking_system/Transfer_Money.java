    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
                                          
String receiverAccount = Recever.getText().trim();
String amountText = amounts.getText().trim();
String senderAccount = Your_account.getText().trim();
String pin = Your_pin.getText().trim();

if (receiverAccount.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please enter Receiver Account Number");
    return;
}
if (amountText.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please enter Amount");
    return;
}
if (senderAccount.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please enter Your Account Number");
    return;
}
if (pin.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please enter PIN");
    return;
}

Connection con = null;

try {
    double amount = Double.parseDouble(amountText);

    if (amount <= 0) {
        JOptionPane.showMessageDialog(this, "Amount must be greater than 0");
        return;
    }

    if (senderAccount.equals(receiverAccount)) {
        JOptionPane.showMessageDialog(this, "You cannot transfer money to your own account");
        return;
    }

    con = DriverManager.getConnection(
            "jdbc:mysql://localhost:3306/online_banking", "root", "root");

    con.setAutoCommit(false);

    double senderBalance;
    String receiverName;

    // Sender verify (PIN ke saath)
    String senderSql = "SELECT balance FROM customers WHERE account_no=? AND pin=?";
    try (PreparedStatement psSender = con.prepareStatement(senderSql)) {
        psSender.setString(1, senderAccount);
        psSender.setString(2, pin);

        try (ResultSet rsSender = psSender.executeQuery()) {
            if (!rsSender.next()) {
                JOptionPane.showMessageDialog(this, "Invalid Account Number or PIN");
                con.rollback();
                return;
            }
            senderBalance = rsSender.getDouble("balance");
        }
    }

    if (senderBalance < amount) {
        JOptionPane.showMessageDialog(this, "Insufficient Balance");
        con.rollback();
        return;
    }

    // Receiver check
    String receiverSql = "SELECT name FROM customers WHERE account_no=?";
    try (PreparedStatement psReceiver = con.prepareStatement(receiverSql)) {
        psReceiver.setString(1, receiverAccount);

        try (ResultSet rsReceiver = psReceiver.executeQuery()) {
            if (!rsReceiver.next()) {
                JOptionPane.showMessageDialog(this, "Receiver Account Not Found");
                con.rollback();
                return;
            }
            receiverName = rsReceiver.getString("name");
        }
    }

    // Sender balance minus
    String debitSql = "UPDATE customers SET balance = balance - ? WHERE account_no=?";
    try (PreparedStatement psDebit = con.prepareStatement(debitSql)) {
        psDebit.setDouble(1, amount);
        psDebit.setString(2, senderAccount);
        psDebit.executeUpdate();
    }

    // Receiver balance plus
    String creditSql = "UPDATE customers SET balance = balance + ? WHERE account_no=?";
    try (PreparedStatement psCredit = con.prepareStatement(creditSql)) {
        psCredit.setDouble(1, amount);
        psCredit.setString(2, receiverAccount);
        psCredit.executeUpdate();
    }

    double newSenderBalance = senderBalance - amount;

    // Transaction log - Debit entry (sender)
    String txnSql = "INSERT INTO transactions "
            + "(account_no, transaction_type, amount, balance_after, transaction_date) "
            + "VALUES (?, ?, ?, ?, ?)";
    try (PreparedStatement psTxn = con.prepareStatement(txnSql)) {
        psTxn.setString(1, senderAccount);
        psTxn.setString(2, "Transfer Debit");
        psTxn.setBigDecimal(3, BigDecimal.valueOf(amount));
        psTxn.setBigDecimal(4, BigDecimal.valueOf(newSenderBalance));
        psTxn.setTimestamp(5, new java.sql.Timestamp(System.currentTimeMillis()));
        psTxn.executeUpdate();
    }
    

    // Dono update + log successful -> commit
    con.commit();

    JOptionPane.showMessageDialog(this,
            "₹" + amount + " transferred successfully to " + receiverName);

    // Sender ki updated details wapas dikhana
    String sql = "SELECT name, account_no, balance FROM customers WHERE account_no = ?";
    try (PreparedStatement pst = con.prepareStatement(sql)) {
        pst.setString(1, senderAccount);

        try (ResultSet rs = pst.executeQuery()) {
            if (rs.next()) {
                account.setText(rs.getString("account_no"));
                name.setText(rs.getString("name"));
                Blance.setText("₹ " + rs.getString("balance"));
            }
        }
    }

    amounts.setText("");

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(this, "Please enter a valid amount");

} catch (Exception e) {

    e.printStackTrace();

    if (con != null) {
        try {
            con.rollback();
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }

    JOptionPane.showMessageDialog(this, "Transfer Failed: " + e.getMessage());

} finally {
    if (con != null) {
        try {
            con.close();
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }
}
    }//GEN-LAST:event_jButton1ActionPerformed

