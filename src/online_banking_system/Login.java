    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
       


    String accountText = account.getText().trim();
    String pin = new String(Pin.getPassword()).trim();

    // Account Number check
    if (accountText.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter Account Number"
        );
        return;
    }

    // PIN check
    if (pin.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter PIN"
        );
        return;
    }

    try {

        // Account number ko number me convert karna
        long accountNo = Long.parseLong(accountText);

        // MySQL Connection
        Connection con = DriverManager.getConnection(
            "jdbc:mysql://localhost:3306/online_banking",
            "root",
            "root"
        );

        // Account Number + PIN verify
        String sql = "SELECT account_no, name, account_type, balance "
                   + "FROM customers "
                   + "WHERE account_no = ? AND pin = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setLong(1, accountNo);
        pst.setString(2, pin);

        ResultSet rs = pst.executeQuery();

        // Login successful
        if (rs.next()) {

            String loggedInAccountNo =
                    rs.getString("account_no");

            // Home page open
            Home_page home =
                    new Home_page(loggedInAccountNo);
            

            home.setVisible(true);
            

            // Login page close
            this.dispose();

        } else {

            JOptionPane.showMessageDialog(
                this,
                "Invalid Account Number or PIN"
            );
        }

        // Close resources
        rs.close();
        pst.close();
        con.close();

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Account Number must contain only numbers"
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
            this,
            "Database Error: " + e.getMessage()
        );
    }        
    }//GEN-LAST:event_jButton1ActionPerformed

