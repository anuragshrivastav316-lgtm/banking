    private void loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginActionPerformed
        // TODO add your handling code here:
        String userId = user_id.getText().trim();
        String password = new String(pass.getPassword());

        if (userId.isEmpty() || password.isEmpty()) {
            error.setText("Enter the login id and password.");
            return;
        }

        try {
            if (userId.equals("anurag") && password.equals("anurag@123")) {

                Admin_page obj = new Admin_page();
                obj.setVisible(true);
                this.setVisible(false);

            } else {
                error.setText("Invalid ID or password.");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,"Something went wrong: " + e.getMessage());
        }

    }//GEN-LAST:event_loginActionPerformed

